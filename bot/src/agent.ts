const MAX_ITERATIONS = 8;

/**
 * Прогоняет одно сообщение клиента через модель. Возвращает текст ответа для
 * отправки в Директ (побочные эффекты — карточки, заказ, вызов менеджера —
 * выполняются внутри инструментов). Историю пишем прямо в session.messages.
 */
/** Скачивает фото клиента, уменьшает (≤1536px, JPEG) и даёт image-блок модели.
 *  Уменьшение нужно, чтобы фото клиента не нарушало лимит 2000px в запросах, где
 *  мы одновременно показываем много фото-кандидатов из каталога. */
async function fetchImageBlock(url: string): Promise<Anthropic.ImageBlockParam | null> {
  try {
    const res = await fetch(url, { redirect: 'follow' });
    if (!res.ok) return null;
    const input = Buffer.from(await res.arrayBuffer());
    if (input.byteLength < 100) return null;
    // failOn:'none' — не падаем на «битых»/нестандартных JPEG (частый случай с
    // картинками из мессенджеров), иначе модель осталась бы без фото клиента.
    const out = await sharp(input, { failOn: 'none' })
      .rotate()
      .resize({ width: 1536, height: 1536, fit: 'inside', withoutEnlargement: true })
      .jpeg({ quality: 80 })
      .toBuffer();
    return { type: 'image', source: { type: 'base64', media_type: 'image/jpeg', data: out.toString('base64') } };
  } catch {
    return null;
  }
}

export async function runAgent(
  session: Session,
  userText: string,
  ctx: ToolContext,
  imageUrls: string[] = [],
): Promise<string> {
  // Если клиент прислал фото — прикрепляем их к сообщению, чтобы модель «видела».
  if (imageUrls.length) {
    const blocks: Anthropic.ContentBlockParam[] = [];
    for (const url of imageUrls) {
      const b = await fetchImageBlock(url);
      if (b) blocks.push(b);
    }
    const gotImages = blocks.length;
    console.error(`[runAgent] фото клиента: ${gotImages}/${imageUrls.length} загружено`);
    blocks.push({
      type: 'text',
      text:
        gotImages > 0
          ? userText ||
            'Клієнт надіслав фото. Подивись, що це за модель (бренд, сімейство, тип покриття, крій, колір), і підбери ТУ Ж модель з нашого каталогу через match_photo.'
          : (userText
              ? userText + '\n\n[Фото не вдалося відкрити. Попроси клієнта надіслати фото ще раз — НЕ питай, що на ньому.]'
              : '[Клієнт надіслав фото, але воно не завантажилось. Попроси надіслати ще раз. НЕ питай у клієнта, що за модель/тип — ти маєш бачити фото сам.]'),
    });
    session.messages.push({ role: 'user', content: blocks });
  } else {
    session.messages.push({ role: 'user', content: userText });
  }
  trimHistory(session);

  let reply = '';
  for (let i = 0; i < MAX_ITERATIONS; i++) {
    const message = await client.messages.create({
      model: config.model,
      max_tokens: 8000,
      thinking: { type: 'adaptive' },
      system: SYSTEM,
      tools: TOOLS,
      messages: session.messages,
    });

    // Сохраняем ответ ассистента целиком (включая блоки размышлений — это важно
    // для последующих запросов с thinking + tool use).
    session.messages.push({ role: 'assistant', content: message.content });

    const toolUses = message.content.filter(
      (b): b is Anthropic.ToolUseBlock => b.type === 'tool_use',
    );

    // Собираем текстовые блоки этого ответа (могут быть и вместе с tool_use).
    const textNow = message.content
      .filter((b): b is Anthropic.TextBlock => b.type === 'text')
      .map((b) => b.text)
      .join('\n')
      .trim();
    if (textNow) reply = textNow;

    if (toolUses.length === 0) break; // модель закончила ход

    const results: Anthropic.ToolResultBlockParam[] = [];
    for (const tu of toolUses) {
      const out = await executeTool(tu.name, (tu.input || {}) as Record<string, unknown>, ctx);
      results.push({ type: 'tool_result', tool_use_id: tu.id, content: out });
    }
    session.messages.push({ role: 'user', content: results });
  }

  return reply.trim();
}
