// Дешёвый локальный фильтр намерений (без ИИ, без затрат токенов).
// Задача: не тратить деньги на троллей/болтовню. Определяем, есть ли в
// сообщении намёк на покупку, и является ли оно явным «мусором».

function norm(s: string): string {
  return (s || '').toLowerCase().replace(/ё/g, 'е').replace(/[’'`]/g, "'").trim();
}

// Признаки интереса к покупке (товар, бренд, размер, намерение).
const BUY_WORDS = [
  'бутс', 'сороконож', 'сороконіж', 'багатошип', 'многошип', 'футзал', 'носк', 'шкарпет',
  'гетр', 'щитк', 'фіксатор', 'фиксатор', 'мяч', "м'яч", 'вратар', 'воротар', 'термо',
  'сумк', 'обув', 'взутт', 'кросов', 'копочк', 'копи',
  'nike', 'adidas', 'puma', 'mizuno', 'найк', 'адид', 'адід', 'пума', 'мизуно',
  'куп', 'замов', 'заказ', 'цена', 'ціна', 'скільк', 'сколько', 'размер', 'розмір',
  'налич', 'наявн', 'доставк', 'оплат', 'почем', 'почём', 'вартіст', 'грн', 'есть',
  'маєте', 'хочу', 'потрібн', 'нужн', 'беру', 'оформ', 'фото', 'модель',
];

// Явный «мусор»: мат, смех, обесценивание.
const JUNK_PATTERNS: RegExp[] = [
  /а?ха+х/, /хаха/, /\bлол\b/, /\blol\b/, /\bкек\b/, /ржу/, /\bору\b/,
  /поху[ийея]/, /поф(и|і)г/, /шляп/, /ф(и|і)гн/, /хрень/, /\bлох\b/, /дурак/, /дебіл/, /дебил/,
  /\bбля/, /ху[йиея]\b/, /пизд/, /еба[тлн]/, /\bсука\b/, /нахуй/, /пош[её]л ты/, /го[вн]но/,
  /долбо/, /придур/, /\bжри\b/,
];

const SIZE_RE = /\b(2[5-9]|3\d|4[0-8])\b/; // размеры обуви 25–48

/** Есть ли в сообщении намёк на покупку/подбор товара. */
export function hasBuyingSignal(text: string): boolean {
  const t = norm(text);
  if (!t) return false;
  if (SIZE_RE.test(t)) return true;
  return BUY_WORDS.some((w) => t.includes(w));
}

/** Явный мусор (мат/смех/троллинг) без намёка на покупку. */
export function isClearJunk(text: string): boolean {
  const t = norm(text);
  if (!t) return false;
  if (hasBuyingSignal(t)) return false;
  if (JUNK_PATTERNS.some((re) => re.test(t))) return true;
  // Только эмодзи/знаки (нет ни одной буквы) — тоже мусор.
  if (!/[a-zа-яіїєґ]/i.test(t)) return true;
  return false;
}
