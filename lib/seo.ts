export function websiteJsonLd() {
  const base = siteUrl();
  return {
    '@context': 'https://schema.org',
    '@type': 'WebSite',
    name: SITE_NAME,
    url: base,
    inLanguage: 'uk',
    potentialAction: {
      '@type': 'SearchAction',
      target: `${base}/catalog?q={search_term_string}`,
      'query-input': 'required name=search_term_string',
    },
  };
}

export function breadcrumbJsonLd(items: { name: string; url: string }[]) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: items.map((it, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: it.name,
      item: it.url,
    })),
  };
}

export function productJsonLd(p: Product, url: string, brand: string | null) {
  const base = siteUrl();
  // Абсолютный URL картинки: productImageSrc даёт /photos/… либо /api/img?src=…
  const image = `${base}${productImageSrc(p.image)}`;
  return {
    '@context': 'https://schema.org',
    '@type': 'Product',
    name: p.name,
    image: [image],
    sku: p.code || p.id,
    ...(brand ? { brand: { '@type': 'Brand', name: brand } } : {}),
    ...(p.country ? { countryOfOrigin: p.country } : {}),
    offers: {
      '@type': 'Offer',
      url,
      priceCurrency: 'UAH',
      price: p.finalPrice,
      availability: p.anyInStock
        ? 'https://schema.org/InStock'
        : 'https://schema.org/OutOfStock',
      seller: { '@type': 'Organization', name: SITE_NAME },
    },
  };
}

export function articleJsonLd(a: {
  title: string;
  description: string;
  date: string;
  url: string;
}) {
  const base = siteUrl();
  return {
    '@context': 'https://schema.org',
    '@type': 'BlogPosting',
    headline: a.title,
    description: a.description,
    datePublished: a.date,
    dateModified: a.date,
    inLanguage: 'uk',
    mainEntityOfPage: a.url,
    image: [`${base}/logo.svg`],
    author: { '@type': 'Organization', name: SITE_NAME, url: base },
    publisher: {
      '@type': 'Organization',
      name: SITE_NAME,
      logo: { '@type': 'ImageObject', url: `${base}/logo.svg` },
    },
  };
}

export function faqJsonLd(items: { q: string; a: string }[]) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: items.map((it) => ({
      '@type': 'Question',
      name: it.q,
      acceptedAnswer: { '@type': 'Answer', text: it.a },
    })),
  };
}

/** Готовый <script> тег с JSON-LD (строкой) для вставки в JSX. */
export function jsonLdScript(data: unknown): string {
  return JSON.stringify(data).replace(/</g, '\\u003c');
}
