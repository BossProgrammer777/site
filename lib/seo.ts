export interface CategorySeoRich {
  howTo: { title: string; text: string };
  kinds: { title: string; text: string };
  brandsBlock: { title: string; text: string };
  faqTitle: string;
  faq: { question: string; answer: string }[];
}

/** Локализованный структурированный контент категории (или undefined). */
export function categorySeoRich(slug: string, locale: Locale): CategorySeoRich | undefined {
  const r = CATEGORY_RICH[slug];
  if (!r) return undefined;
  const s = (x: RichSection) => ({ title: x.title[locale], text: x.text[locale] });
  return {
    howTo: s(r.howTo),
    kinds: s(r.kinds),
    brandsBlock: s(r.brandsBlock),
    faqTitle: r.faqTitle[locale],
    faq: r.faq.map((f) => ({ question: f.q[locale], answer: f.a[locale] })),
  };
}

